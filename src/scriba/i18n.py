def t(lang: str, key: str) -> str:
    table = TEXTS.get(lang) or TEXTS[DEFAULT_LANG]
    return table.get(key) or TEXTS["en"].get(key, key)


def language_choices(lang: str, languages: list[str]) -> list[tuple[str, str]]:
    """Dropdown (label, value) pairs; values stay canonical English names."""
    names = LANGUAGE_NAMES_IT if lang == "it" else {}
    return [(t(lang, "auto_detect"), "auto")] + [(names.get(x, x), x) for x in languages]
